"""Download-source providers. The first provider reads GitHub Releases.

Rules enforced here:
- Only repositories explicitly listed in the catalog are considered; repository
  names are never guessed from game titles.
- Source-code archives generated by GitHub are not build assets and are ignored.
- Only .zip assets are reported as installable (the install pipeline supports
  ZIP). Other formats are reported with a reason instead of being downloaded.
- Draft releases are ignored. Pre-releases are used only when no stable release
  has a usable Windows build.
"""

from __future__ import annotations

import fnmatch
import re
import time
from dataclasses import dataclass, field
from typing import Any, Callable
from urllib.parse import urlparse

import requests

GITHUB_API = "https://api.github.com"
GITHUB_HOSTS = {"github.com", "www.github.com"}
REQUEST_TIMEOUT = (10, 20)
CACHE_TTL_SECONDS = 15 * 60
_OWNER_RE = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})$")
_REPO_RE = re.compile(r"^[A-Za-z0-9._-]{1,100}$")
_SOURCE_ARCHIVE_RE = re.compile(r"^(source[\s_-]*code|src)\b|(\.tar\.gz|\.tgz)$", re.I)
# Asset names are split into lowercase tokens and classified by operating system.
# "x64" alone is deliberately NOT a Windows signal: "Game-Linux-x64.zip" is a Linux build.
_TOKEN_SPLIT = re.compile(r"[^a-z0-9]+")
_WINDOWS_TOKENS = {"win", "windows", "win32", "win64", "winx64", "winx86", "msvc"}
_OTHER_OS_TOKENS = {"linux", "appimage", "deb", "rpm", "mac", "macos", "osx", "darwin", "apple",
                    "android", "apk", "steamdeck", "switch", "ps2", "ps3", "ps4", "wii", "wasm", "web"}


def classify_os(name: str) -> str:
    """'windows', 'other' (Linux, macOS, consoles...) or '' when the name says nothing.
    Any non-Windows token wins, so a mixed name is never installed as Windows."""
    tokens = {tok for tok in _TOKEN_SPLIT.split(name.lower()) if tok}
    if tokens & _OTHER_OS_TOKENS:
        return "other"
    if tokens & _WINDOWS_TOKENS:
        return "windows"
    return ""


class ReleaseError(RuntimeError):
    """A release lookup failed. `kind` lets the UI show a precise message."""

    def __init__(self, kind: str, message: str) -> None:
        super().__init__(message)
        self.kind = kind  # no_repo | not_found | rate_limited | network | no_release | bad_response


@dataclass(frozen=True)
class ReleaseAsset:
    name: str
    download_url: str
    size: int | None
    is_zip: bool
    is_windows_hint: bool
    os_hint: str = ""  # 'windows', 'other' or '' (unknown)
    sha256: str = ""  # from the GitHub API "digest" field, when published


@dataclass(frozen=True)
class ReleaseInfo:
    tag: str
    name: str
    prerelease: bool
    published_at: str
    html_url: str
    assets: tuple[ReleaseAsset, ...] = field(default_factory=tuple)


@dataclass(frozen=True)
class ResolvedBuild:
    """The outcome of resolving a project to a downloadable Windows build."""
    provider: str
    repository: str  # owner/repo
    release: ReleaseInfo
    asset: ReleaseAsset | None  # None when no suitable asset exists
    reason: str = ""  # human-readable explanation when asset is None


def parse_github_repo(url: str) -> tuple[str, str] | None:
    """Return (owner, repo) for an https://github.com/owner/repo URL, else None."""
    if not url:
        return None
    parsed = urlparse(url)
    if parsed.scheme != "https" or parsed.hostname not in GITHUB_HOSTS:
        return None
    parts = [p for p in parsed.path.split("/") if p]
    if len(parts) < 2:
        return None
    owner, repo = parts[0], parts[1]
    if repo.endswith(".git"):
        repo = repo[:-4]
    if not _OWNER_RE.match(owner) or not _REPO_RE.match(repo) or repo in {".", ".."}:
        return None
    return owner, repo


def _is_source_archive(name: str) -> bool:
    return bool(_SOURCE_ARCHIVE_RE.search(name))


def _parse_release(raw: dict[str, Any]) -> ReleaseInfo:
    assets = []
    for item in raw.get("assets") or []:
        if not isinstance(item, dict) or item.get("state", "uploaded") != "uploaded":
            continue
        name = str(item.get("name") or "")
        url = str(item.get("browser_download_url") or "")
        if not name or urlparse(url).scheme != "https":
            continue
        if _is_source_archive(name):
            continue
        size = item.get("size")
        digest = str(item.get("digest") or "")
        sha = digest.split(":", 1)[1].lower() if digest.startswith("sha256:") else ""
        if not re.fullmatch(r"[0-9a-f]{64}", sha or "0" * 64):
            sha = ""
        assets.append(ReleaseAsset(
            name=name,
            download_url=url,
            size=size if isinstance(size, int) and size >= 0 else None,
            is_zip=name.lower().endswith(".zip"),
            is_windows_hint=classify_os(name) == "windows",
            os_hint=classify_os(name),
            sha256=sha,
        ))
    return ReleaseInfo(
        tag=str(raw.get("tag_name") or ""),
        name=str(raw.get("name") or raw.get("tag_name") or ""),
        prerelease=bool(raw.get("prerelease")),
        published_at=str(raw.get("published_at") or ""),
        html_url=str(raw.get("html_url") or ""),
        assets=tuple(assets),
    )


def asset_matches(pattern: str, asset_name: str) -> bool:
    """Case-insensitive glob on a release file name. Only .zip files can be installed."""
    name = asset_name.lower()
    return name.endswith(".zip") and fnmatch.fnmatch(name, pattern.lower())


def choose_by_pattern(release: ReleaseInfo, pattern: str) -> ReleaseAsset | None:
    matches = sorted((a for a in release.assets if asset_matches(pattern, a.name)), key=lambda a: a.name)
    return matches[0] if matches else None


def choose_windows_zip(release: ReleaseInfo) -> ReleaseAsset | None:
    candidates = [a for a in release.assets if a.is_zip and a.os_hint == "windows"]
    if not candidates:
        return None
    # When several Windows archives exist, prefer the 64-bit one.
    candidates.sort(key=lambda a: (0 if "64" in a.name else 1, a.name))
    return candidates[0]


def _explain_missing_windows_build(release: ReleaseInfo) -> str:
    """Short, accurate reason for the UI. Used inside '...: {reason}.'"""
    assets = release.assets
    if not assets:
        return "the latest release has no downloadable build assets"
    has_windows = any(a.os_hint == "windows" for a in assets)
    if not has_windows and any(a.os_hint == "other" for a in assets):
        return "the latest release only publishes non-Windows builds"
    if any(a.os_hint == "windows" and not a.is_zip for a in assets):
        return "the Windows build is not a .zip archive"
    return "no Windows build is listed in the latest release"


class GitHubReleaseProvider:
    name = "github"

    def __init__(self, http_get: Callable[..., requests.Response] | None = None,
                 clock: Callable[[], float] = time.monotonic) -> None:
        self._get = http_get or requests.get
        self._clock = clock
        self._cache: dict[str, tuple[float, list[ReleaseInfo]]] = {}

    def supports(self, repository_url: str) -> bool:
        return parse_github_repo(repository_url) is not None

    def resolve(self, repository_url: str, asset_pattern: str = "") -> ResolvedBuild:
        repo = parse_github_repo(repository_url)
        if repo is None:
            raise ReleaseError("no_repo", "no supported GitHub repository is listed")
        owner, name = repo
        slug = f"{owner}/{name}"
        releases = self._releases(slug)
        if not releases:
            raise ReleaseError("no_release", "the repository has no published releases")

        stable = [r for r in releases if not r.prerelease]
        ordered = stable + [r for r in releases if r.prerelease]
        for release in ordered:
            # A user's filter decides the file itself; otherwise the Windows detection applies.
            asset = choose_by_pattern(release, asset_pattern) if asset_pattern else choose_windows_zip(release)
            if asset is not None:
                return ResolvedBuild(self.name, slug, release, asset)

        newest = releases[0]
        reason = _explain_missing_windows_build(newest)
        return ResolvedBuild(self.name, slug, newest, None, reason)

    def _releases(self, slug: str) -> list[ReleaseInfo]:
        now = self._clock()
        cached = self._cache.get(slug)
        if cached and now - cached[0] < CACHE_TTL_SECONDS:
            return cached[1]
        url = f"{GITHUB_API}/repos/{slug}/releases"
        try:
            response = self._get(
                url,
                params={"per_page": 10},
                timeout=REQUEST_TIMEOUT,
                headers={"Accept": "application/vnd.github+json",
                         "X-GitHub-Api-Version": "2022-11-28",
                         "User-Agent": "NoldeLauncher/0.1"},
            )
        except requests.RequestException as exc:
            raise ReleaseError("network", f"network error: {exc.__class__.__name__}") from exc

        if response.status_code == 404:
            raise ReleaseError("not_found", "the repository was not found or is private")
        if response.status_code in (403, 429):
            remaining = response.headers.get("X-RateLimit-Remaining")
            if response.status_code == 429 or remaining == "0":
                raise ReleaseError("rate_limited", "GitHub API rate limit reached; try again later")
            raise ReleaseError("not_found", "GitHub refused access to this repository")
        if response.status_code != 200:
            raise ReleaseError("network", f"GitHub returned HTTP {response.status_code}")
        try:
            data = response.json()
        except ValueError as exc:
            raise ReleaseError("bad_response", "GitHub returned an unreadable response") from exc
        if not isinstance(data, list):
            raise ReleaseError("bad_response", "unexpected GitHub response shape")

        releases = [_parse_release(r) for r in data
                    if isinstance(r, dict) and not r.get("draft")]
        self._cache[slug] = (now, releases)
        return releases
